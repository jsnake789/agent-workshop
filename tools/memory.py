#!/usr/bin/env python3
"""File-based memory graph: validate, index, query and export.

Nodes are markdown files at memory/nodes/<type>/<slug>.md with YAML frontmatter.
See memory/README.md for the format. Requires PyYAML.
"""
import argparse
import datetime as dt
import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
MEM = ROOT / "memory"
NODES = MEM / "nodes"
WIKILINK = re.compile(r"\[\[([a-z]+/[a-z0-9-]+)\]\]")
SLUG = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")


def load_schema():
    return yaml.safe_load((MEM / "schema.yaml").read_text())


def parse(path):
    text = path.read_text()
    if not text.startswith("---"):
        raise ValueError(f"{path}: missing frontmatter")
    _, fm, body = text.split("---", 2)
    meta = yaml.safe_load(fm) or {}
    meta["_body"] = body.strip()
    meta["_path"] = path
    return meta


def load_nodes():
    nodes = {}
    for p in sorted(NODES.glob("*/*.md")):
        n = parse(p)
        nodes[n.get("id", f"{p.parent.name}/{p.stem}")] = n
    return nodes


def edges(nodes):
    out = []
    for nid, n in nodes.items():
        for link in n.get("links") or []:
            out.append({"from": nid, "rel": link["rel"], "to": link["to"],
                        **{k: v for k, v in link.items() if k not in ("rel", "to")}})
        for target in sorted(set(WIKILINK.findall(n["_body"]))):
            out.append({"from": nid, "rel": "mentions", "to": target})
    return out


def validate(_args=None):
    schema = load_schema()
    types, rels = schema["node_types"], schema["relations"]
    nodes, errors = load_nodes(), []
    for nid, n in nodes.items():
        p = n["_path"].relative_to(ROOT)
        expected = f"{n['_path'].parent.name}/{n['_path'].stem}"
        if n.get("id") != expected:
            errors.append(f"{p}: id '{n.get('id')}' should be '{expected}'")
        if n.get("type") not in types:
            errors.append(f"{p}: unknown type '{n.get('type')}'")
        elif n.get("type") != n["_path"].parent.name:
            errors.append(f"{p}: type '{n['type']}' doesn't match folder")
        if not SLUG.match(n["_path"].stem):
            errors.append(f"{p}: slug must be kebab-case")
        for field in ("title", "summary", "created", "updated"):
            if not n.get(field):
                errors.append(f"{p}: missing '{field}'")
        if n.get("status") and n["status"] not in schema["statuses"]:
            errors.append(f"{p}: unknown status '{n['status']}'")
    for e in edges(nodes):
        src = nodes[e["from"]]["_path"].relative_to(ROOT)
        if e["to"] not in nodes:
            errors.append(f"{src}: link to missing node '{e['to']}' ({e['rel']})")
            continue
        rule = rels.get(e["rel"])
        if rule is None:
            errors.append(f"{src}: unknown relation '{e['rel']}' (add it to schema.yaml)")
            continue
        ft, tt = nodes[e["from"]]["type"], nodes[e["to"]]["type"]
        if rule["from"] != "*" and ft not in rule["from"]:
            errors.append(f"{src}: '{e['rel']}' can't start from a {ft}")
        if rule["to"] != "*" and tt not in rule["to"]:
            errors.append(f"{src}: '{e['rel']}' can't point to a {tt}")
    for err in errors:
        print("ERROR", err)
    print(f"{len(nodes)} nodes, {len(edges(nodes))} edges, {len(errors)} errors")
    return 1 if errors else 0


def index(_args=None):
    nodes = load_nodes()
    lines = ["# Memory index", "",
             "Generated by `tools/memory.py index`. Do not edit by hand.", ""]
    by_type = {}
    for nid, n in nodes.items():
        by_type.setdefault(n["type"], []).append(n)
    for t in sorted(by_type):
        lines += [f"## {t}", ""]
        for n in sorted(by_type[t], key=lambda x: x["id"]):
            status = "" if n.get("status", "active") == "active" else f" _({n['status']})_"
            lines.append(f"- `{n['id']}` **{n['title']}**{status}: {n.get('summary', '')}")
        lines.append("")
    (MEM / "INDEX.md").write_text("\n".join(lines))
    print(f"Wrote memory/INDEX.md ({len(nodes)} nodes)")
    return 0


def neighbours(nodes, nid):
    es = edges(nodes)
    return ([e for e in es if e["from"] == nid], [e for e in es if e["to"] == nid])


def show(args):
    nodes = load_nodes()
    if args.id not in nodes:
        print(f"No node '{args.id}'", file=sys.stderr)
        return 1
    print(nodes[args.id]["_path"].read_text())
    out, inc = neighbours(nodes, args.id)
    print("## Outgoing")
    for e in out:
        print(f"- {e['rel']} -> {e['to']}")
    print("## Incoming")
    for e in inc:
        print(f"- {e['from']} -[{e['rel']}]->")
    return 0


def context(args):
    """Breadth-first subgraph around one or more nodes, as compact markdown."""
    nodes, es = load_nodes(), None
    es = edges(nodes)
    seen, frontier = set(args.ids), list(args.ids)
    for _ in range(args.depth):
        nxt = []
        for nid in frontier:
            for e in es:
                other = e["to"] if e["from"] == nid else e["from"] if e["to"] == nid else None
                if other and other in nodes and other not in seen:
                    seen.add(other)
                    nxt.append(other)
        frontier = nxt
    print(f"# Context: {', '.join(args.ids)} (depth {args.depth}, {len(seen)} nodes)\n")
    for nid in args.ids + sorted(seen - set(args.ids)):
        if nid not in nodes:
            continue
        n = nodes[nid]
        print(f"## {nid}: {n['title']}")
        print(n.get("summary", ""))
        if nid in args.ids or args.full:
            print("\n" + n["_body"])
        rel = [f"{e['rel']} -> {e['to']}" for e in es if e["from"] == nid and e["to"] in seen]
        if rel:
            print("Links: " + "; ".join(rel))
        print()
    return 0


def search(args):
    q = args.query.lower()
    for nid, n in load_nodes().items():
        hay = " ".join([nid, n.get("title", ""), n.get("summary", ""),
                        " ".join(n.get("tags") or []), n["_body"]]).lower()
        if q in hay:
            print(f"{nid}: {n.get('summary', '')}")
    return 0


def new(args):
    schema = load_schema()
    if args.type not in schema["node_types"]:
        print(f"Unknown type. Choose from: {', '.join(schema['node_types'])}", file=sys.stderr)
        return 1
    slug = args.slug or re.sub(r"[^a-z0-9]+", "-", args.title.lower()).strip("-")
    path = NODES / args.type / f"{slug}.md"
    if path.exists():
        print(f"{path.relative_to(ROOT)} already exists", file=sys.stderr)
        return 1
    today = dt.date.today().isoformat()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"""---
id: {args.type}/{slug}
type: {args.type}
title: {args.title}
status: active
created: {today}
updated: {today}
tags: []
summary: TODO one line
links: []
---

""")
    print(path.relative_to(ROOT))
    return 0


def cypher_value(v):
    if isinstance(v, (int, float, bool)):
        return json.dumps(v)
    if isinstance(v, list):
        return "[" + ", ".join(cypher_value(x) for x in v) + "]"
    return json.dumps(str(v))


def export(args):
    nodes = load_nodes()
    es = edges(nodes)
    props = lambda n: {k: (str(v) if isinstance(v, dt.date) else v)
                       for k, v in n.items() if not k.startswith("_") and k != "links"}
    if args.format == "json":
        json.dump({"nodes": [{**props(n), "body": n["_body"]} for n in nodes.values()],
                   "edges": es}, sys.stdout, indent=2, default=str)
        print()
    else:
        print("// Generated by tools/memory.py export --format cypher")
        print("CREATE CONSTRAINT node_id IF NOT EXISTS FOR (n:Node) REQUIRE n.id IS UNIQUE;")
        for n in nodes.values():
            label = n["type"].capitalize()
            p = {**props(n), "body": n["_body"]}
            sets = ", ".join(f"n.{k} = {cypher_value(v)}" for k, v in p.items() if k != "id")
            print(f"MERGE (n:Node {{id: {cypher_value(n['id'])}}}) SET n:{label}, {sets};")
        for e in es:
            if e["to"] not in nodes:
                continue
            rel = e["rel"].upper()
            print(f"MATCH (a:Node {{id: {cypher_value(e['from'])}}}), (b:Node {{id: {cypher_value(e['to'])}}}) "
                  f"MERGE (a)-[:{rel}]->(b);")
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("validate").set_defaults(fn=validate)
    sub.add_parser("index").set_defaults(fn=index)
    s = sub.add_parser("show"); s.add_argument("id"); s.set_defaults(fn=show)
    c = sub.add_parser("context"); c.add_argument("ids", nargs="+")
    c.add_argument("--depth", type=int, default=1)
    c.add_argument("--full", action="store_true", help="include bodies of neighbours too")
    c.set_defaults(fn=context)
    q = sub.add_parser("search"); q.add_argument("query"); q.set_defaults(fn=search)
    n = sub.add_parser("new"); n.add_argument("type"); n.add_argument("title")
    n.add_argument("--slug"); n.set_defaults(fn=new)
    x = sub.add_parser("export"); x.add_argument("--format", choices=["json", "cypher"], default="json")
    x.set_defaults(fn=export)
    args = ap.parse_args()
    sys.exit(args.fn(args))


if __name__ == "__main__":
    main()
